#!/usr/bin/env python3
"""Generate exact hv_* signatures from the linked Boot Kernel Collection.

KDK symbols locate functions within __TEXT. The embedded kernel UUID must match
that of the KDK before translating those offsets into the collection. Using KC
bytes preserves exact runtime checks despite RIP-relative data relocations.

usage: gen_kernsyms.py <kdk kernel> <out header> <boot kc>
"""
import struct
import subprocess
import sys
from pathlib import Path

FUNCS = [
    "hv_set_traps", "hv_release_traps",
    "hv_set_callbacks", "hv_release_callbacks",
    "hv_set_task_target", "hv_set_thread_target",
    "hv_get_task_target", "hv_get_thread_target",
    # Kick IPI used by AppleHV's vcpu_interrupt; not exported to third-party kexts.
    "mp_cpus_kick",
    # AppleHV tests this before each entry: an AST needs the user boundary.
    "hv_ast_pending",
]
ANCHOR_FUNC = "IOLog"
NBYTES = 24


def commands(data, base=0):
    magic, cpu, _, _, ncmds, sizeofcmds, _, _ = struct.unpack_from("<IiiIIIII", data, base)
    if magic != 0xFEEDFACF or cpu != 0x01000007:
        raise ValueError("expected x86_64 Mach-O")
    off, end = base + 32, base + 32 + sizeofcmds
    if end > len(data):
        raise ValueError("truncated load commands")
    for _ in range(ncmds):
        if off + 8 > end:
            raise ValueError("truncated load command")
        cmd, size = struct.unpack_from("<II", data, off)
        if size < 8 or off + size > end:
            raise ValueError("invalid load command size")
        yield cmd, off, size
        off += size


def segments(data, base=0):
    result = {}
    for cmd, off, size in commands(data, base):
        if cmd == 0x19:
            if size < 72:
                raise ValueError("truncated segment")
            name = data[off + 8:off + 24].split(b"\0")[0].decode()
            result[name] = struct.unpack_from("<QQQQ", data, off + 24)
    return result


def read_va(data, segs, va, n):
    for vmaddr, _, fileoff, filesize in segs.values():
        if vmaddr <= va and va + n <= vmaddr + filesize:
            off = fileoff + va - vmaddr
            if off + n > len(data):
                raise ValueError("segment extends past file")
            return data[off:off + n]
    raise ValueError(f"unmapped address {va:#x}")


def macho_uuid(data, base=0):
    for cmd, off, size in commands(data, base):
        if cmd == 0x1B and size == 24:
            return data[off + 8:off + 24]
    raise ValueError("missing Mach-O UUID")


def kernel_entry(data):
    if struct.unpack_from("<I", data, 12)[0] != 0xC:
        raise ValueError("expected MH_FILESET kernel collection")
    for cmd, off, size in commands(data):
        if cmd == 0x80000035 and size >= 32:
            _, fileoff, nameoff, _ = struct.unpack_from("<QQII", data, off + 8)
            if not 32 <= nameoff < size:
                raise ValueError("invalid fileset entry name offset")
            name = data[off + nameoff:off + size].split(b"\0")[0]
            if name == b"com.apple.kernel":
                return fileoff
    raise ValueError("com.apple.kernel missing from collection")


def linked_text(kernel, collection):
    base = kernel_entry(collection)
    if macho_uuid(kernel) != macho_uuid(collection, base):
        raise ValueError("KDK and KC kernel UUIDs differ; use the matching KDK")
    original = segments(kernel)["__TEXT"]
    linked = segments(collection, base)["__TEXT"]
    if original[1] != linked[1]:
        raise ValueError("KDK and KC kernel __TEXT sizes differ")
    return original, linked, segments(collection, base)


def translate_text(va, n, original, linked):
    offset = va - original[0]
    if offset < 0 or offset + n > min(original[3], linked[3]):
        raise ValueError(f"symbol {va:#x} outside kernel __TEXT")
    return linked[0] + offset


def main():
    kernel_path, out, kc_path = sys.argv[1:]
    kernel, collection = Path(kernel_path).read_bytes(), Path(kc_path).read_bytes()
    original, linked, kc_segments = linked_text(kernel, collection)
    syms = {}
    for line in subprocess.run(["nm", kernel_path], capture_output=True, text=True, check=True).stdout.splitlines():
        p = line.split()
        if len(p) == 3 and p[2].startswith("_"):
            syms.setdefault(p[2][1:], int(p[0], 16))
    version = next((chunk.decode() for chunk in kernel.split(b"\0")
                    if chunk.startswith(b"Darwin Kernel Version")), None)
    if not version or version.encode() + b"\0" not in collection:
        raise ValueError("kernel version missing from KDK or KC")
    anchor = translate_text(syms[ANCHOR_FUNC], NBYTES, original, linked)
    lines = [
        "// Generated by tools/gen_kernsyms.py from matching KDK + Boot KC. Do not edit.",
        f"// Kernel UUID: {macho_uuid(kernel).hex()}",
        "#pragma once", "#include <stdint.h>", "", "namespace kernsyms {",
        f'static const char kVersion[] = "{version}";',
        f"static const uint64_t kAnchorFunc = 0x{anchor:x}ULL; // {ANCHOR_FUNC} in KC",
        f"static const unsigned kSigLen = {NBYTES};", "",
        "struct Func { const char *name; uint64_t unslid; uint8_t sig[kSigLen]; };",
        "enum FuncId {",
    ]
    lines += [f"    F_{f}," for f in FUNCS] + ["    F_COUNT", "};", "static const Func kFuncs[F_COUNT] = {"]
    for name in FUNCS:
        va = translate_text(syms[name], NBYTES, original, linked)
        code = read_va(collection, kc_segments, va, NBYTES)
        hexb = ", ".join(f"0x{x:02x}" for x in code)
        lines.append(f'    {{"{name}", 0x{va:x}ULL, {{{hexb}}}}},')
    lines += ["};", "} // namespace kernsyms", ""]
    Path(out).write_text("\n".join(lines))
    print(f"wrote {out}: {len(FUNCS)} functions, matching kernel UUID {macho_uuid(kernel).hex()}")


if __name__ == "__main__":
    main()
